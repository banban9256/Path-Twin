def generate_nodes():
    rows = []
    for nid, name, ntype, lat, lon in NODE_DEFS:
        rows.append({
            "node_id": nid,
            "name": name,
            "type": ntype,
            "latitude": lat,
            "longitude": lon,
        })
    return pd.DataFrame(rows)


def generate_edges():
    rows = []
    for e in EDGE_DEFS:
        start, end, dist, slope, stairs, cw, width, conf, curb, remarks = e
        rows.append({
            "start_node": start,
            "end_node": end,
            "distance_m": float(dist),
            "slope_type": slope,
            "stairs_count": stairs,
            "crosswalk": cw,
            "sidewalk_width": width,
            "confidence": conf,
            "remarks": remarks,
            "curb": curb,
        })
    return pd.DataFrame(rows)


def save_csvs(node_df, edge_df):
    os.makedirs(CSV_DIR, exist_ok=True)
    node_df.to_csv(NODE_CSV, index=False, encoding="utf-8-sig")
    edge_df.to_csv(EDGE_CSV, index=False, encoding="utf-8-sig")
    print(f"[OK] Saved {len(node_df)} nodes -> {NODE_CSV}")
    print(f"[OK] Saved {len(edge_df)} edges -> {EDGE_CSV}")


def insert_to_db(node_df, edge_df):
    conn = sqlite3.connect(DB_PATH)
    cur = conn.cursor()
    cur.execute("DELETE FROM edge")
    cur.execute("DELETE FROM node")
    conn.commit()
    node_df.to_sql("node", conn, if_exists="append", index=False)
    edge_df.to_sql("edge", conn, if_exists="append", index=False)
    conn.commit()
    conn.close()
    print(f"[OK] Inserted into DB")


if __name__ == "__main__":
    node_df = generate_nodes()
    edge_df = generate_edges()
    save_csvs(node_df, edge_df)
    insert_to_db(node_df, edge_df)
    print("\n--- Nodes ---")
    print(node_df.to_string(index=False))
    print(f"\n--- Edges ({len(edge_df)} total) ---")
    print(edge_df.to_string(index=False))
