function getSegmentKey(startId, endId) {
  return `${startId}|${endId}`;
}

function getWaypoints(startId, endId) {
  const forward =
    SEGMENT_WAYPOINTS[getSegmentKey(startId, endId)];

  if (forward) {
    return forward;
  }

  const reverse =
    SEGMENT_WAYPOINTS[getSegmentKey(endId, startId)];

  if (reverse) {
    return [...reverse].reverse();
  }

  return [];
}

export function getFloorMap(floor) {
  return FLOOR_MAPS[floor] ?? FLOOR_MAPS[1];
}

export function getNodePosition(nodeId) {
  return NODE_POSITIONS[nodeId] ?? null;
}

export function getPathNodesForFloor(path = [], floor) {
  if (!Array.isArray(path)) {
    return [];
  }

  const result = [];

  for (let index = 0; index < path.length; index += 1) {
    const nodeId = path[index];
    const position = NODE_POSITIONS[nodeId];

    if (!position || position.floor !== floor) {
      continue;
    }

    if (result.length > 0) {
      const previousRealNode = [...result]
        .reverse()
        .find((node) => !node.isWaypoint);

      if (previousRealNode) {
        const waypoints = getWaypoints(
          previousRealNode.nodeId,
          nodeId,
        );

        waypoints.forEach((point, waypointIndex) => {
          result.push({
            nodeId:
              `waypoint-${floor}-` +
              `${previousRealNode.nodeId}-` +
              `${nodeId}-${waypointIndex}`,
            floor,
            x: point.x,
            y: point.y,
            label: "",
            isWaypoint: true,
          });
        });
      }
    }

    result.push({
      nodeId,
      ...position,
      isWaypoint: false,
    });
  }

  return result;
}